<?php

declare(strict_types=1);

namespace NhanAZ\CustomAlerts;

use JsonException;
use RuntimeException;
use ZipArchive;
use function array_keys;
use function file_exists;
use function file_get_contents;
use function file_put_contents;
use function hash;
use function implode;
use function is_array;
use function is_int;
use function is_string;
use function json_decode;
use function json_encode;
use function ksort;
use function mkdir;
use function preg_replace_callback;
use function rename;
use function rtrim;
use function str_replace;

final class LanguagePackBuilder{
	private const HEADER_UUID = "3122cbb1-2fcb-4af5-8c78-8d4f2d77f35e";
	private const MODULE_UUID = "701fc7c6-3f1d-47d9-bc7b-5f00f58b9a30";

	/**
	 * @param array<string, array<string, string>> $translations Locale => translation key => value
	 * @throws JsonException|RuntimeException
	 */
	public static function build(string $dataFolder, array $translations) : string{
		foreach(array_keys($translations) as $locale){
			$localeTranslations = $translations[$locale];
			ksort($localeTranslations);
			$translations[$locale] = $localeTranslations;
		}
		ksort($translations);

		$content = json_encode($translations, JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
		$contentHash = hash("sha256", $content);
		if(!file_exists($dataFolder) && !mkdir($dataFolder, 0777, true) && !file_exists($dataFolder)){
			throw new RuntimeException("Could not create the plugin data folder");
		}

		$statePath = rtrim($dataFolder, "/\\") . DIRECTORY_SEPARATOR . "language-pack-state.json";
		$state = self::readState($statePath);
		$version = $state["hash"] === $contentHash ? $state["version"] : [1, 0, $state["version"][2] + 1];
		$packPath = rtrim($dataFolder, "/\\") . DIRECTORY_SEPARATOR . "customalerts-language-" . $contentHash . ".mcpack";

		if(!self::isValidPack($packPath)){
			if(file_exists($packPath)){
				unlink($packPath);
			}
		self::writePack($packPath, $version, $translations);
		}

		$newState = json_encode(["hash" => $contentHash, "version" => $version], JSON_THROW_ON_ERROR);
		if(file_put_contents($statePath, $newState) === false){
			throw new RuntimeException("Could not save resource pack version state");
		}
		return $packPath;
	}

	/** @return array{hash: string, version: array{int, int, int}} */
	private static function readState(string $statePath) : array{
		if(file_exists($statePath)){
			$data = json_decode((string) file_get_contents($statePath), true);
			if(is_array($data) && isset($data["hash"], $data["version"]) && is_string($data["hash"]) &&
				is_array($data["version"]) && count($data["version"]) === 3 &&
				is_int($data["version"][0]) && is_int($data["version"][1]) && is_int($data["version"][2])
			){
				return ["hash" => $data["hash"], "version" => $data["version"]];
			}
		}
		return ["hash" => "", "version" => [1, 0, 0]];
	}

	private static function isValidPack(string $path) : bool{
		if(!file_exists($path)){
			return false;
		}
		$archive = new ZipArchive();
		if($archive->open($path) !== true){
			return false;
		}
		$isValid = $archive->locateName("manifest.json") !== false && $archive->locateName("texts/languages.json") !== false;
		$archive->close();
		return $isValid;
	}

	/**
	 * @param array{int, int, int} $version
	 * @param array<string, array<string, string>> $translations
	 * @throws RuntimeException
	 */
	private static function writePack(string $packPath, array $version, array $translations) : void{
		$temporaryPath = $packPath . ".tmp";
		$archive = new ZipArchive();
		$result = $archive->open($temporaryPath, ZipArchive::CREATE | ZipArchive::OVERWRITE);
		if($result !== true){
			throw new RuntimeException("Could not create generated language resource pack (ZipArchive code $result)");
		}

		$manifest = [
			"format_version" => 2,
			"header" => [
				"name" => "CustomAlerts Language Overrides",
				"description" => "Language strings generated by the CustomAlerts plugin.",
				"uuid" => self::HEADER_UUID,
				"version" => $version,
				"min_engine_version" => [1, 26, 60]
			],
			"modules" => [[
				"type" => "resources",
				"uuid" => self::MODULE_UUID,
				"version" => $version
			]]
		];
		$locales = array_keys($translations);
		$files = [
			"manifest.json" => json_encode($manifest, JSON_THROW_ON_ERROR | JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES),
			"texts/languages.json" => json_encode($locales, JSON_THROW_ON_ERROR | JSON_PRETTY_PRINT)
		];
		foreach(array_keys($translations) as $locale){
			$entries = $translations[$locale];
			$files["texts/$locale.lang"] = self::encodeLanguageFile($entries);
		}
		foreach(array_keys($files) as $name){
			$contents = $files[$name];
			if(!$archive->addFromString($name, $contents)){
				$archive->close();
				throw new RuntimeException("Could not add $name to generated language resource pack");
			}
		}
		if(!$archive->close()){
			throw new RuntimeException("Could not finish generated language resource pack");
		}
		if(!rename($temporaryPath, $packPath)){
			throw new RuntimeException("Could not finalize generated language resource pack");
		}
	}

	/** @param array<string, string> $entries */
	private static function encodeLanguageFile(array $entries) : string{
		$lines = [];
		foreach(array_keys($entries) as $key){
			$value = $entries[$key];
			$value = preg_replace_callback('/\{%([0-9]+)\}|\{([0-9]+)\}/', static function(array $matches) : string{
				$index = (int) ($matches[1] !== "" ? $matches[1] : $matches[2]);
				return "%" . ($index + 1) . '$s';
			}, $value) ?? $value;
			$value = str_replace(["\\", "\r", "\n"], ["\\\\", "", "\\n"], $value);
			$lines[] = "$key=$value";
		}
		return implode("\n", $lines) . "\n";
	}
}
