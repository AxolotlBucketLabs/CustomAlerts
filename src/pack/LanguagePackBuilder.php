<?php

declare(strict_types=1);

namespace AxolotlBucketLabs\CustomAlerts\pack;

use JsonException;
use RuntimeException;
use ZipArchive;
use function array_keys;
use function array_map;
use function count;
use function file_exists;
use function file_get_contents;
use function file_put_contents;
use function glob;
use function hash;
use function implode;
use function is_array;
use function is_dir;
use function is_int;
use function is_string;
use function json_decode;
use function json_encode;
use function ksort;
use function mkdir;
use function preg_replace_callback;
use function rename;
use function rtrim;
use function str_replace;
use function unlink;

final class LanguagePackBuilder{
	private const string HEADER_UUID = "3122cbb1-2fcb-4af5-8c78-8d4f2d77f35e";
	private const string MODULE_UUID = "701fc7c6-3f1d-47d9-bc7b-5f00f58b9a30";
	private const string PACK_PREFIX = "customalerts-language-";

	private string $directory;

	public function __construct(string $directory){
		$this->directory = rtrim($directory, "/\\");
	}

	/**
	 * @param array<string, array<string, string>> $translations
	 * @throws JsonException|RuntimeException
	 */
	public function build(array $translations) : string{
		foreach($translations as $locale => $entries){
			ksort($entries);
			$translations[$locale] = $entries;
		}
		ksort($translations);

		$content = json_encode($translations, JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
		$contentHash = hash("sha256", $content);
		if(!is_dir($this->directory) && !mkdir($this->directory, 0777, true) && !is_dir($this->directory)){
			throw new RuntimeException("Could not create $this->directory");
		}

		$statePath = $this->directory . DIRECTORY_SEPARATOR . "language-pack-state.json";
		$state = self::readState($statePath);
		$version = $state["hash"] === $contentHash ? $state["version"] : [1, 0, $state["version"][2] + 1];
		$packPath = $this->directory . DIRECTORY_SEPARATOR . self::PACK_PREFIX . $contentHash . ".mcpack";

		if(!self::isValidPack($packPath)){
			if(file_exists($packPath)){
				unlink($packPath);
			}
			self::writePack($packPath, $version, $translations);
		}

		if(file_put_contents($statePath, json_encode(["hash" => $contentHash, "version" => $version], JSON_THROW_ON_ERROR)) === false){
			throw new RuntimeException("Could not save resource pack version state");
		}
		$this->removeStalePacks($packPath);
		return $packPath;
	}

	private function removeStalePacks(string $currentPath) : void{
		$paths = glob($this->directory . DIRECTORY_SEPARATOR . self::PACK_PREFIX . "*.mcpack");
		foreach($paths === false ? [] : $paths as $path){
			if($path !== $currentPath){
				@unlink($path);
			}
		}
	}

	/**
	 * @return array{hash: string, version: array{int, int, int}}
	 */
	private static function readState(string $statePath) : array{
		$contents = file_exists($statePath) ? file_get_contents($statePath) : false;
		$data = $contents !== false ? json_decode($contents, true) : null;
		if(is_array($data) && is_string($data["hash"] ?? null) && is_array($data["version"] ?? null) && count($data["version"]) === 3){
			[$major, $minor, $patch] = [$data["version"][0] ?? null, $data["version"][1] ?? null, $data["version"][2] ?? null];
			if(is_int($major) && is_int($minor) && is_int($patch)){
				return ["hash" => $data["hash"], "version" => [$major, $minor, $patch]];
			}
		}
		return ["hash" => "", "version" => [1, 0, 0]];
	}

	private static function isValidPack(string $path) : bool{
		if(!file_exists($path)){
			return false;
		}
		$archive = new ZipArchive();
		if($archive->open($path) !== true){
			return false;
		}
	$valid = $archive->locateName("manifest.json") !== false && $archive->locateName("texts/languages.json") !== false && $archive->locateName("texts/language_names.json") !== false;
		$archive->close();
		return $valid;
	}

	/**
	 * @param array{int, int, int}                 $version
	 * @param array<string, array<string, string>> $translations
	 * @throws JsonException|RuntimeException
	 */
	private static function writePack(string $packPath, array $version, array $translations) : void{
		$temporaryPath = $packPath . ".tmp";
		$archive = new ZipArchive();
		$result = $archive->open($temporaryPath, ZipArchive::CREATE | ZipArchive::OVERWRITE);
		if($result !== true){
			throw new RuntimeException("Could not create generated language resource pack (ZipArchive code $result)");
		}

		$manifest = [
			"format_version" => 2,
			"header" => [
				"name" => "CustomAlerts Language Overrides",
				"description" => "Language strings generated by the CustomAlerts plugin.",
				"uuid" => self::HEADER_UUID,
				"version" => $version,
				"min_engine_version" => [1, 26, 60]
			],
			"modules" => [[
				"type" => "resources",
				"uuid" => self::MODULE_UUID,
				"version" => $version
			]]
		];
		$files = [
			"manifest.json" => json_encode($manifest, JSON_THROW_ON_ERROR | JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES),
			"texts/languages.json" => json_encode(array_keys($translations), JSON_THROW_ON_ERROR | JSON_PRETTY_PRINT),
			"texts/language_names.json" => json_encode(array_map(static fn(string $locale) : array => [$locale, BundledLocaleFiles::NAMES[$locale] ?? $locale], array_keys($translations)), JSON_THROW_ON_ERROR | JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE)
		];
		foreach($translations as $locale => $entries){
			$files["texts/$locale.lang"] = self::encodeLanguageFile($entries);
		}
		foreach($files as $name => $contents){
			if(!$archive->addFromString($name, $contents)){
				$archive->close();
				throw new RuntimeException("Could not add $name to generated language resource pack");
			}
		}
		if(!$archive->close()){
			throw new RuntimeException("Could not finish generated language resource pack");
		}
		if(!rename($temporaryPath, $packPath)){
			throw new RuntimeException("Could not finalize generated language resource pack");
		}
	}

	/**
	 * @param array<string, string> $entries
	 */
	private static function encodeLanguageFile(array $entries) : string{
		$lines = [];
		foreach($entries as $key => $value){
			$value = preg_replace_callback('/\{%([0-9]+)}|\{([0-9]+)}/', static function(array $matches) : string{
				$index = (int) ($matches[1] !== "" ? $matches[1] : $matches[2]);
				return "%" . ($index + 1) . '$s';
			}, $value) ?? $value;
			$value = str_replace(["\\", "\r", "\n"], ["\\\\", "", "\\n"], $value);
			$lines[] = "$key=$value";
		}
		return implode("\n", $lines) . "\n";
	}
}
